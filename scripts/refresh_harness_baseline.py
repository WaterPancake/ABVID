#!/usr/bin/env python
"""Regenerate tests/harness_baseline.json (HUMAN-RUN ONLY).

Measures the collected test count for BOTH dependency environments (uv extras
"cast" and "baseline") and hashes the frozen files, then writes
tests/harness_baseline.json.

Each environment is measured in its OWN uv environment (uv run --extra <name>
--isolated), because the two extras conflict by design and collect different
test sets.

Run this only when the test suite shape legitimately changes, in the same
commit as the change, and call it out in the PR description. A CI failure on
the canary always means "suite shape changed" — a human must review the
tests/ diff before merging.

Usage (from the repo root, in either environment):
    uv run --extra cast scripts/refresh_harness_baseline.py
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BASELINE_FILE = REPO_ROOT / "tests" / "harness_baseline.json"

# Test modules that import baseline-extra-only dependencies (librosa/sklearn);
# they do not collect under the cast extra and are excluded there.
BASELINE_ONLY_MODULES = (
    "tests/test_h1.py",
    "tests/test_simulation.py",
    "tests/test_benchmark_prototype.py",
)

# Files frozen by the roadmap — the files a reward-hacking agent would most
# benefit from quietly editing (the lockfile pins the environments; the
# protocol registry pins the experiment definitions).
FROZEN_FILES = [
    "uv.lock",
    "configs/experiments/admission.json",
    "configs/experiments/r0_reproduction.json",
    "configs/experiments/h1_baselines.json",
    "configs/experiments/h2_simulation.json",
    "configs/experiments/cast_coverage.json",
    "configs/experiments/cast_grouped_coverage.json",
]

ENVIRONMENTS = ("cast", "baseline")


def selection_args(environment: str) -> list[str]:
    args = ["-m", "not archive"]
    if environment == "cast":
        args += [f"--ignore={m}" for m in BASELINE_ONLY_MODULES]
    return args


def collected_test_count(environment: str) -> int:
    """Count tests in the environment's own isolated uv environment."""
    command = [
        "uv", "run", "--locked", "--extra", environment, "--isolated",
        "python", "-m", "pytest",
        "--collect-only", "-q", "--no-header",
        *selection_args(environment),
    ]
    result = subprocess.run(
        command, cwd=REPO_ROOT, capture_output=True, text=True, timeout=600,
    )
    if result.returncode != 0:
        raise SystemExit(
            f"Collection failed in the {environment} environment "
            f"(exit {result.returncode}):\n{result.stdout[-1500:]}\n"
            f"{result.stderr[-1500:]}"
        )
    per_file = re.findall(r"^(\S+\.py): (\d+)$", result.stdout, re.M)
    if per_file:
        total = sum(int(count) for _, count in per_file)
        return total
    # "N/M tests collected (K deselected)": N is the selected count.
    match = re.search(r"(\d+)(?:/\d+)? tests? collected", result.stdout)
    if match:
        return int(match.group(1))
    raise SystemExit(
        f"Could not parse collect output (env={environment}):\n"
        f"{result.stdout[-2000:]}\n{result.stderr[-2000:]}"
    )


def main() -> None:
    environments = {}
    for name in ENVIRONMENTS:
        environments[name] = {"test_count": collected_test_count(name)}
        print(f"{name}: {environments[name]['test_count']} tests collected")
    hashes = {}
    for rel in FROZEN_FILES:
        path = REPO_ROOT / rel
        if not path.exists():
            raise SystemExit(f"frozen file listed in FROZEN_FILES is missing: {rel}")
        hashes[rel] = hashlib.sha256(path.read_bytes()).hexdigest()
    payload = {
        "environments": environments,
        "file_hashes": hashes,
        "note": (
            "Regenerated by scripts/refresh_harness_baseline.py. Update only in "
            "the same commit as a legitimate suite/frozen-file change, with the "
            "change called out in the PR description."
        ),
    }
    BASELINE_FILE.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(f"baseline written: {len(hashes)} frozen files")
    print(f"-> {BASELINE_FILE}")


if __name__ == "__main__":
    main()
